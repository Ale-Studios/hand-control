// Builds the small gesture icons of the Controls / Gestures tabs: each one is the hand SKELETON as the app draws it (thin
// lines, joints, bright fingertips), made from the same fake hands the tests use, so every icon shows exactly the pose the
// engine recognises.   node scripts/gen-gesture-icons.mjs   →   src/renderer/gesture-icons.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeHand } from '../test/helpers/synth.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CONN = [[0, 1], [1, 2], [2, 3], [3, 4], [0, 5], [5, 6], [6, 7], [7, 8], [5, 9], [9, 10], [10, 11], [11, 12], [9, 13], [13, 14], [14, 15], [15, 16], [13, 17], [17, 18], [18, 19], [19, 20], [0, 17]];
const TIPS = [4, 8, 12, 16, 20];
const PALM = [0, 1, 5, 9, 13, 17];
const TILT = -0.45; // seen a little from above, so curled fingers show as short stubs over the knuckles (a flat front view hides them)

/** Projects the world points (metres) of a right hand as seen in the mirrored preview. */
function project(pose) {
  const { wl } = makeHand({ pose });
  const c = Math.cos(TILT), s = Math.sin(TILT);
  return wl.map((p) => ({ x: -p.x, y: p.y * c - p.z * s }));
}

function svg(parts, box, extra = '') {
  const pad = 0.012;
  const [x0, y0, x1, y1] = [box.x0 - pad, box.y0 - pad, box.x1 + pad, box.y1 + pad];
  const side = Math.max(x1 - x0, y1 - y0);
  const cx = (x0 + x1) / 2, cy = (y0 + y1) / 2;
  const k = 40 / side; // 40 x 40 view box
  const X = (x) => +((x - cx) * k + 20).toFixed(1), Y = (y) => +((y - cy) * k + 20).toFixed(1);
  let out = '';
  for (const pts of parts) {
    out += `<polygon class="p" points="${PALM.map((i) => X(pts[i].x) + ',' + Y(pts[i].y)).join(' ')}"/>`;
    out += `<path class="l" d="${CONN.map(([a, b]) => `M${X(pts[a].x)} ${Y(pts[a].y)}L${X(pts[b].x)} ${Y(pts[b].y)}`).join('')}"/>`;
    out += pts.map((p, i) => `<circle class="${TIPS.includes(i) ? 't' : 'j'}" cx="${X(p.x)}" cy="${Y(p.y)}" r="${TIPS.includes(i) ? 1.7 : 1.05}"/>`).join('');
  }
  return `<svg class="gi" viewBox="0 0 40 40" aria-hidden="true">${out}${extra}</svg>`;
}

const bounds = (parts) => {
  const all = parts.flat();
  return { x0: Math.min(...all.map((p) => p.x)), y0: Math.min(...all.map((p) => p.y)), x1: Math.max(...all.map((p) => p.x)), y1: Math.max(...all.map((p) => p.y)) };
};

const icons = {};
for (const pose of ['open', 'point', 'pinch', 'rclick', 'scroll', 'ringpinch', 'pinkypinch', 'fist']) {
  const pts = project(pose);
  icons[pose] = svg([pts], bounds([pts]));
}
// fist + move: the fist with a small "move" arrow
{
  const pts = project('fist');
  const b = bounds([pts]);
  const w = b.x1 - b.x0;
  icons.fistmove = svg([pts], { ...b, x1: b.x1 + w * 0.45 }, '<path class="a" d="M31 20h7M35.5 17.5l2.5 2.5-2.5 2.5"/>');
}
// two hands: two open hands side by side
{
  const a = project('open'), b = project('point').map((p) => ({ x: -p.x + 0.13, y: p.y }));
  icons.two = svg([a, b], bounds([a, b]));
}

const file = path.join(root, 'src', 'renderer', 'gesture-icons.mjs');
fs.writeFileSync(file, '// GENERATED by scripts/gen-gesture-icons.mjs — the hand skeleton of each gesture, drawn like the app draws a tracked hand.\n'
  + 'export const ICONS = ' + JSON.stringify(icons, null, 1) + ';\n');
console.log('wrote', path.relative(root, file), Object.keys(icons).join(', '));
